package network

import (
	"context"
	"net"
	"os"
	"path/filepath"
	"testing"
)

func TestHasNameserver(t *testing.T) {
	dir := t.TempDir()
	for _, tc := range []struct {
		content string
		want    bool
	}{
		{"", false},
		{"# generated by gokrazy/dhcp\ndomain lan\n", false},
		{"nameserver\n", false},
		{"# generated by gokrazy/dhcp\nnameserver 8.8.8.8\nnameserver 1.1.1.1\n", true},
		{"  nameserver 192.168.31.1  \n", true},
	} {
		p := filepath.Join(dir, "resolv.conf")
		if err := os.WriteFile(p, []byte(tc.content), 0o644); err != nil {
			t.Fatal(err)
		}
		if got := hasNameserver(p); got != tc.want {
			t.Errorf("hasNameserver(%q) = %v, want %v", tc.content, got, tc.want)
		}
	}
	if hasNameserver(filepath.Join(dir, "missing")) {
		t.Error("hasNameserver(missing file) = true")
	}
}

func TestUpstreamDialer(t *testing.T) {
	// A UDP socket standing in for the upstream DNS server, and one for the
	// server resolv.conf names.
	upstream, err := net.ListenPacket("udp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer upstream.Close()
	listed, err := net.ListenPacket("udp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer listed.Close()

	resolv := filepath.Join(t.TempDir(), "resolv.conf")
	dial := upstreamDialer(resolv, []string{upstream.LocalAddr().String()})
	remote := func(address string) string {
		t.Helper()
		c, err := dial(context.Background(), "udp", address)
		if err != nil {
			t.Fatal(err)
		}
		defer c.Close()
		return c.RemoteAddr().String()
	}

	// No resolv.conf, then one without nameservers (as /proc/net/pnp on a
	// DHCP network): Go's fallback to localhost goes to the upstream.
	if got, want := remote("127.0.0.1:53"), upstream.LocalAddr().String(); got != want {
		t.Errorf("without resolv.conf: dialed %s, want upstream %s", got, want)
	}
	if err := os.WriteFile(resolv, nil, 0o644); err != nil {
		t.Fatal(err)
	}
	if got, want := remote("127.0.0.1:53"), upstream.LocalAddr().String(); got != want {
		t.Errorf("with an empty resolv.conf: dialed %s, want upstream %s", got, want)
	}

	// Once DHCP has written nameservers, the resolver's choice stands.
	if err := os.WriteFile(resolv, []byte("nameserver 127.0.0.1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if got, want := remote(listed.LocalAddr().String()), listed.LocalAddr().String(); got != want {
		t.Errorf("with nameservers: dialed %s, want %s", got, want)
	}
}
